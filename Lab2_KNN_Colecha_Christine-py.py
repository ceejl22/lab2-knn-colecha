import pandas as pd
import numpy as np

data = { "Weight": [51,62,69,64,65,56,58,57,55],
        "Height": [167,182,176,173,172,174,169,173,170],
         "Class": ["Underweight", "Normal", "Normal", "Normal", "Normal", "Underweight", "Normal", "Underweight", "Normal"]
         }
df= pd.DataFrame(data)
print("DATASET")
print(df)

new_weight = 57
new_height = 170

print("\nData to classify:")
print("Weight=", new_weight)
print("Weight=", new_height)

k = int(input("\nEnter K value:"))

euclidean = []
manhattan = []
minkowski = []

p = 3

for i, row in df.iterrows():
    x = row["Weight"]
    y = row["Height"]

    # Euclidean Distance
    d_eucledian = np.sqrt(
        (x - new_weight)**2 + (y - new_height)**2
    )
    # Manhattan Distance
    d_manhattan = (
        abs(x - new_weight) + abs(y - new_height)
    )
    # Minskowski Distance
    d_minkowski = (
        abs(x - new_weight)**p + abs(y - new_height)**p
    )** (1/p)

    euclidean.append(d_eucledian)
    manhattan.append(d_manhattan)
    minkowski.append(d_minkowski)

df ["Euclidean"] = euclidean
df ["Manhattan"] = manhattan
df ["Minkowski"] = minkowski

print("\nAll Distance Computations:")
print(df.round(4))

"""KNN COMPUTATION"""

# STORE FINAL RESULTS
results = {}

# KNN FOR EACH DISTANCE METHOD
for method in ["Euclidean", "Manhattan", "Minkowski"]:
    print("\n----------------------------------------")
    print(method.upper())
    print("----------------------------------------")

    # Sort from smallest distance
    sorted_data = df.sort_values(method)

    # Get K nearest neighbors
    nearest = sorted_data.head(k)
    print("\nK Nearest Neighbors:")
    print( nearest[["Weight", "Height", "Class", method] ].round(4))


    # COUNT THE CLASSES
    class_count = nearest["Class"].value_counts()
    print("\nClass Count:")
    for class_name, count in class_count.items():
        print(class_name, "=", count)


    # CHECK HIGHEST COUNT
    highest = class_count.max()
    tied_classes = class_count[class_count == highest].index.tolist()


    # IF THERE IS NO TIE
    if len(tied_classes) == 1:
        prediction = tied_classes[0]
        print("\nClassification =", prediction)


    # IF THERE IS A TIE
    else:
        print("\nThere is a tie!")
        scores = {}
        for class_name in tied_classes:
            score = 0
            class_rows = nearest[
                nearest["Class"] == class_name]
            for distance in class_rows[method]:
                if distance == 0:
                    score = float("inf")
                else:
                    score = score + (1 / distance)
            scores[class_name] = score

            print(class_name,"score =",round(score, 4))
        prediction = max(scores, key=scores.get)
        print("\nClassification after tie breaking =", prediction)

    # SAVE RESULT
    results[method] = prediction


# FINAL RESULT
print("\n========================================")
print("FINAL CLASSIFICATION")
print("========================================")
print( "New Weight =",new_weight,
      "|New Height =", new_height)
print("\nEuclidean :", results["Euclidean"])
print("Manhattan :", results["Manhattan"])
print("Minkowski :", results["Minkowski"])
print("========================================")